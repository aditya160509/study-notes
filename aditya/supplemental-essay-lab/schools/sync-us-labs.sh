#!/bin/sh
# Rebuilds combined-us-labs.md from the US school lab files. Edit the individual files, not the combined one.
set -eu
d=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
{
  printf '# US Supplement Research Labs (combined)\n\n> Generated by `sync-us-labs.sh` from the individual lab files. Do not edit here.\n\n'
  printf 'Order: MIT, Stanford, UIUC, UMD, Purdue, UMass Amherst, Virginia Tech, ASU Barrett.\n'
  for f in mit stanford uiuc umd purdue umass-amherst virginia-tech asu-barrett; do
    printf '\n\n---\n\n'
    cat "$d/$f.md"
  done
} > "$d/combined-us-labs.md"
